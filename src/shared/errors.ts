type Catalog = (typeof ERRORS)['zh-CN'];
export type ErrorKey = keyof Catalog;
type ParamsOf<K extends ErrorKey> = Catalog[K] extends (params: infer P) => string ? [params: P] : [];
export type ErrorArgs = { [K in ErrorKey]: [key: K, ...params: ParamsOf<K>] }[ErrorKey];

export type PlainErrorKey = { [K in ErrorKey]: ParamsOf<K> extends [] ? K : never }[ErrorKey];

export const isPlainErrorKey = (key: string): key is PlainErrorKey =>
  Object.hasOwn(ERRORS['zh-CN'], key) && typeof ERRORS['zh-CN'][key as ErrorKey] === 'string';

export function translateError(locale: Locale, ...[key, params]: ErrorArgs | [key: PlainErrorKey]): string {
  const entry: string | ((p: never) => string) = ERRORS[locale][key];
  return typeof entry === 'function' ? entry(params as never) : entry;
}
